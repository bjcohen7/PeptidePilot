import fs from "node:fs/promises";
import path from "node:path";
import { generatedBlogPostContent } from "../shared/blog-content.generated";
import { legacyBlogPosts } from "../shared/blog-legacy";
import { pseoContentRecords } from "../shared/pseoContent";
import {
  comparisonPages,
  forConditionPages,
  goalPages,
  guidePages,
  peptidePages,
  reviewPages,
  stackPages,
} from "../shared/pseoData";

const projectRoot = path.resolve(import.meta.dirname, "..");
const dataRoot = path.join(projectRoot, "client", "public", "data");
const blogRoot = path.join(dataRoot, "blog");
const pseoRoot = path.join(dataRoot, "pseo");
const pseoIndexPath = path.join(projectRoot, "shared", "pseoIndex.generated.ts");

async function ensureCleanDir(dirPath: string) {
  await fs.rm(dirPath, { recursive: true, force: true });
  await fs.mkdir(dirPath, { recursive: true });
}

async function writeJsonFile(filePath: string, value: unknown) {
  await fs.mkdir(path.dirname(filePath), { recursive: true });
  await fs.writeFile(filePath, JSON.stringify(value), "utf8");
}

async function exportBlogContent() {
  await ensureCleanDir(blogRoot);

  const generatedPosts = Object.values(generatedBlogPostContent);
  const allPosts = [...generatedPosts, ...legacyBlogPosts];

  await Promise.all(
    allPosts.map((post) =>
      writeJsonFile(path.join(blogRoot, `${post.slug}.json`), post)
    )
  );

  console.log(`[content] exported ${allPosts.length} blog article payloads`);
}

async function exportPseoContent() {
  await ensureCleanDir(pseoRoot);

  const entries = Object.values(pseoContentRecords);

  await Promise.all(
    entries.map((record) => {
      const relativePath = record.path.replace(/^\//, "");
      return writeJsonFile(path.join(pseoRoot, `${relativePath}.json`), record);
    })
  );

  console.log(`[content] exported ${entries.length} pseo content payloads`);
}

