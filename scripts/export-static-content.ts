async function exportPseoIndex() {
  const sections = toPseoIndex();
  const contents = `/* Auto-generated by scripts/export-static-content.ts. */
import type { PseoSection } from "./pseo";

export const pseoSections = ${JSON.stringify(sections, null, 2)} satisfies PseoSection[];
`;

  await fs.writeFile(pseoIndexPath, contents, "utf8");
  console.log(`[content] exported ${sections.length} pseo section indexes`);
}

await fs.mkdir(dataRoot, { recursive: true });
await exportBlogContent();
await exportPseoContent();
await exportPseoIndex();
